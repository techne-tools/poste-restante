-- 034_keyletter.sql
-- The keyletter — a letter that carries a public key (SPEC §15, PLAN-crypto.md
-- item 6). Three schema facts, one story.
--
-- 1. `keyletter` is a letter KIND, not a body convention.
--
--    A letter whose only content is a key should be identifiable without
--    parsing its body; the kind is what the client's vocabulary, the retrieval
--    filter and this CHECK constraint read. The body carries the frame
--    (`format: "keyframe"` — the keys, the human note, the signature over the
--    letter id), and `LetterSchema` refuses a kind/format mismatch in either
--    direction, so the two markers can never disagree. The CHECK is re-added
--    with the new value, exactly as 008/012/013/019/024/025 did.
--
-- 2. `address_keys.origin` says HOW a key record arrived.
--
--    The two paths are not equally proven, and the difference belongs in the
--    row rather than in a comment:
--
--      'registration'  proves possession of the key over a house-issued
--                      challenge (auth/key-proof.ts) under the address's own
--                      session — the address's own act.
--
--      'keyletter'     proves possession of the key over its own LETTER ID, and
--                      nothing more. The sender is the authenticated owner of
--                      the `from` address at the door (every letter face binds
--                      `from` to the caller: HTTP, MCP, SMTP), and the key is
--                      the one the letter publishes. That is TOFU on first
--                      sight, and it is why a keyletter that disagrees with an
--                      existing live key is an offer, never a silent write.
--
--    `source_letter_id` is the provenance pointer — the letter that carried the
--    key. Deliberately NOT a foreign key: a key record outlives the letter that
--    announced it. Deleting a letter is first-class in this house; deleting a
--    key's history is not.
--
--    Nothing here touches `addresses.identity_id`. A keyletter installs a key;
--    it does not establish an identity. The identity is pinned at the address's
--    first PROVEN registration and never moves (033, decision t_fe94e8d8). A
--    key that arrived by TOFU has proven the key, not the address, so it leaves
--    the spine exactly as it was — the address stays resolvable to its handle
--    until it registers with proof. Its sealed letters still verify: the
--    verifier walks the sender's key history, and the keyletter's key is in it.
--
-- 3. `address_key_offers` holds the change a human must see.
--
--    A keyletter from an address whose live key DIFFERS does not overwrite it.
--    Whoever already sealed a letter to the old key needs to know the key
--    moved, so the change waits: one pending offer per address (the newest),
--    resolved by a resident accepting or declining it, or settled as
--    'superseded' when the address registers keys with proof of possession —
--    the address has then spoken for itself, and the offer is moot.
--
--    `letter_id` IS a foreign key, ON DELETE CASCADE: an offer without its
--    letter is not explainable, and the house does not keep what it cannot
--    explain. Offers are state; the letters are the archive.

ALTER TABLE address_keys ADD COLUMN IF NOT EXISTS origin text NOT NULL DEFAULT 'registration';
ALTER TABLE address_keys ADD COLUMN IF NOT EXISTS source_letter_id text;

ALTER TABLE address_keys DROP CONSTRAINT IF EXISTS address_keys_origin_check;
ALTER TABLE address_keys ADD CONSTRAINT address_keys_origin_check
    CHECK (origin IN ('registration', 'keyletter'));

CREATE TABLE IF NOT EXISTS address_key_offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address text NOT NULL REFERENCES addresses (id) ON DELETE CASCADE,
    letter_id text NOT NULL REFERENCES letters (id) ON DELETE CASCADE,
    age_recipient text NOT NULL,
    ed25519_public text NOT NULL,
    recovery_age_recipient text,
    created_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz,
    resolution text CHECK (resolution IN ('accepted', 'declined', 'superseded'))
);

-- One pending offer per address: a newer keyletter that disagrees with the
-- live key replaces the pending one rather than stacking. The resolved rows
-- stay as the record of what was offered and what the house did with it.
CREATE UNIQUE INDEX IF NOT EXISTS address_key_offers_one_pending_idx
    ON address_key_offers (address) WHERE resolved_at IS NULL;

-- The letter is how a resident finds the offer it is being asked about.
CREATE INDEX IF NOT EXISTS address_key_offers_letter_idx
    ON address_key_offers (letter_id);

ALTER TABLE letters DROP CONSTRAINT IF EXISTS letters_kind_check;
ALTER TABLE letters ADD CONSTRAINT letters_kind_check
    CHECK (kind IN ('letter','feed','system','audio','note','task','invite','clause',
                    'leave','join','agent','rename','shelve','unshelve','keyletter'));
