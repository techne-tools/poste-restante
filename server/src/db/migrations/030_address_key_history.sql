-- 030_address_key_history.sql
-- Key history, actually implemented — address_keys becomes append-only (§15).
--
-- 018 stated the invariant and the schema contradicted it. `address_keys`
-- was `PRIMARY KEY (address)`: one row per address. `setAddressKey()`
-- overwrote `age_recipient`, `ed25519_public`, `recovery_age_recipient` and
-- reset `retired_at = NULL`, so re-registering keys DESTROYED the old public
-- key. Every letter already written by that address then failed
-- signature verification, and a re-delivery of one was rejected outright.
-- Nothing in `server/src` ever set `retired_at` to a timestamp: the only
-- writes were NULL and the only reads were `IS NULL`. "Key history" was a
-- comment describing a table that did not keep any.
--
-- What this migration makes true:
--   * A key record is a ROW, not a SLOT. A surrogate `id` is the primary
--     key; `address` becomes ordinary data.
--   * One ACTIVE row per address, enforced structurally — the partial unique
--     index `address_keys_one_active_idx ... WHERE retired_at IS NULL`.
--     Retention is the default: an address may hold any number of retired
--     rows and exactly one live one. No runtime check can drift from that.
--   * Rotation closes, it never overwrites. `setAddressKey()` sets
--     `retired_at = now()` on the live row and appends the next, in one
--     transaction (`server/src/db/repository.ts`).
--   * A `retired_at` row is a record of an identity the address has HELD.
--     Public keys are public: the history is readable exactly like the
--     current record, and the house still holds no private key.
--   * Existing rows become the active rows. Nothing is dropped: each present
--     row is given an id and the partial index sees one live row per address,
--     which is precisely what the old primary key guaranteed. Safe to apply
--     to a populated table (verified against a copy of a populated database).
--
-- WHAT THIS MIGRATION DOES *NOT* DECIDE — the letter id under rotation.
--
-- A letter's id resolves each handle to its ed25519 fingerprint
-- (`server/src/id.ts`) and a sealed letter's signature is over that id. When
-- the sender rotates, the same letter re-delivered would hash to a different
-- id while the signature still names the old one. Two options:
--
--   (a) Keep deriving the id from the CURRENT key, and recover the id the
--       signature was actually made over from the sender's key history at
--       verification time.  <-- implemented here
--   (b) Key the id on a rotation-stable identity (`addresses.identity_id`
--       pinned to the address's first key). That is a change to SPEC §19 and
--       to the OIDC binding, which §19 says re-establishes on the NEW key —
--       so it is Chris's decision, not this card's.
--
-- (a) costs no protocol change: the id is still sha256 over the canonical
-- form with identities resolved, and verification walks the sender's key
-- history newest-first, keeping the id whose signature verifies. Its
-- consequence is recorded rather than hidden: if a party OTHER than the
-- sender has rotated since signing, no candidate id can be re-derived and the
-- letter is rejected. Such a letter was never stored, so nothing in the
-- archive is lost — re-seal and re-sign. (b) stays open; it is raised on the
-- card and in the changelog, not slipped in here.
--
-- Verified behaviour after rotation: a pre-rotation sealed letter still
-- verifies and re-delivers to its ORIGINAL id (no duplicate row); the retired
-- row survives with a non-null `retired_at`; sealing reads the active row;
-- and a keyless legacy address still resolves to its handle.

ALTER TABLE address_keys ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;

-- The old primary key WAS the defect — one slot per address. Replace it with
-- a surrogate; `address` becomes data that repeats across generations.
ALTER TABLE address_keys DROP CONSTRAINT IF EXISTS address_keys_pkey;
ALTER TABLE address_keys ALTER COLUMN id SET NOT NULL;
ALTER TABLE address_keys ADD CONSTRAINT address_keys_pkey PRIMARY KEY (id);

-- Exactly one live record per address; retired records accumulate freely.
CREATE UNIQUE INDEX IF NOT EXISTS address_keys_one_active_idx
    ON address_keys (address) WHERE retired_at IS NULL;

-- Reading an address's history is the verification path: ordered, newest
-- first. (The address book keeps reading only the live row.)
CREATE INDEX IF NOT EXISTS address_keys_history_idx
    ON address_keys (address, created_at DESC);
